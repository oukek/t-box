import type { DatabaseSchema } from '@t-box/server-foundation/persistence/schema'

export const applicationsSchema: DatabaseSchema = {
  id: 'applications',
  tables: [
    `CREATE TABLE application_build_imports (
      app_id varchar(64) NOT NULL,
      version varchar(48) NOT NULL,
      release_id varchar(80) NOT NULL,
      bundle_sha256 char(64) NOT NULL,
      object_url varchar(1000) NOT NULL,
      source json NOT NULL,
      credential_id char(36) NOT NULL,
      created_at datetime(3) NOT NULL DEFAULT (utc_timestamp(3)),
      PRIMARY KEY (app_id,version),
      UNIQUE KEY release_id (release_id)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    `CREATE TABLE application_file_grants (
      user_id char(36) NOT NULL,
      app_id varchar(64) NOT NULL,
      generation int NOT NULL,
      resource_id char(36) NOT NULL,
      created_at datetime(3) NOT NULL DEFAULT (utc_timestamp(3)),
      PRIMARY KEY (user_id,app_id,generation,resource_id),
      KEY app_file_resource (resource_id),
      CONSTRAINT app_file_resource FOREIGN KEY (resource_id) REFERENCES resources (id) ON DELETE CASCADE,
      CONSTRAINT app_file_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    `CREATE TABLE application_import_credentials (
      id char(36) NOT NULL,
      token_hash char(64) NOT NULL,
      administrator_id char(36) NOT NULL,
      apps json NOT NULL,
      expires_at datetime(3) DEFAULT NULL,
      revoked_at datetime(3) DEFAULT NULL,
      created_at datetime(3) NOT NULL DEFAULT (utc_timestamp(3)),
      managed_key varchar(32) DEFAULT NULL,
      PRIMARY KEY (id),
      UNIQUE KEY token_hash (token_hash),
      UNIQUE KEY managed_key (managed_key)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    `CREATE TABLE application_installations (
      user_id char(36) NOT NULL,
      app_id varchar(64) NOT NULL,
      release_id varchar(80) NOT NULL,
      target_release_id varchar(80) DEFAULT NULL,
      generation int unsigned NOT NULL DEFAULT '1',
      status varchar(20) NOT NULL,
      grants json NOT NULL,
      operation_id char(36) DEFAULT NULL,
      updated_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
      error varchar(300) DEFAULT NULL,
      retry_attempts int unsigned NOT NULL DEFAULT '0',
      retry_at datetime(3) DEFAULT NULL,
      PRIMARY KEY (user_id,app_id),
      CONSTRAINT app_install_user_fk FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    `CREATE TABLE application_lifecycle_operations (
      id char(36) NOT NULL,
      user_id char(36) NOT NULL,
      app_id varchar(64) NOT NULL,
      request_key varchar(80) NOT NULL,
      request_hash char(64) NOT NULL,
      release_id varchar(80) NOT NULL,
      generation int unsigned NOT NULL,
      action varchar(16) NOT NULL,
      status varchar(20) NOT NULL DEFAULT 'queued',
      submitted tinyint NOT NULL DEFAULT '0',
      attempts int unsigned NOT NULL DEFAULT '0',
      lease_token char(36) DEFAULT NULL,
      lease_until datetime(3) DEFAULT NULL,
      next_attempt_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
      receipt json DEFAULT NULL,
      error varchar(300) DEFAULT NULL,
      created_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
      updated_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
      PRIMARY KEY (id),
      UNIQUE KEY app_operation_request (user_id,app_id,request_key),
      KEY app_operation_queue (status,next_attempt_at,lease_until),
      CONSTRAINT app_operation_user_fk FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    `CREATE TABLE application_operations (
      user_id char(36) NOT NULL,
      app_id varchar(40) NOT NULL,
      operation_key char(64) NOT NULL,
      payload_hash char(64) NOT NULL,
      response json NOT NULL,
      created_at datetime(3) NOT NULL,
      PRIMARY KEY (user_id,app_id,operation_key),
      CONSTRAINT app_operation_owner_fk FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    `CREATE TABLE application_publication_events (
      id char(36) NOT NULL,
      app_id varchar(64) NOT NULL,
      release_id varchar(80) NOT NULL,
      action varchar(24) NOT NULL,
      administrator_id char(36) NOT NULL,
      detail json NOT NULL,
      created_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
      PRIMARY KEY (id),
      KEY app_publication_history (app_id,created_at)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    `CREATE TABLE application_registry (
      app_id varchar(64) NOT NULL,
      kind varchar(16) NOT NULL,
      created_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
      PRIMARY KEY (app_id)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
    `CREATE TABLE application_releases (
      release_id varchar(80) NOT NULL,
      app_id varchar(64) NOT NULL,
      definition json NOT NULL,
      definition_hash char(64) NOT NULL,
      published tinyint NOT NULL DEFAULT '1',
      created_at datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
      status varchar(16) NOT NULL DEFAULT 'draft',
      revision int unsigned NOT NULL DEFAULT '1',
      release_notes text,
      submitted_by char(36) DEFAULT NULL,
      submitted_at datetime(3) DEFAULT NULL,
      published_by char(36) DEFAULT NULL,
      published_at datetime(3) DEFAULT NULL,
      PRIMARY KEY (release_id),
      KEY application_catalog (app_id,published)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`,
  ],
}
