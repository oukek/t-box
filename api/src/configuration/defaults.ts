export const settingNumber = (
  snapshot: ConfigurationSnapshot | undefined,
  key: string,
  fallback: number,
) =>
  typeof snapshot?.values[key] === 'number'
    ? (snapshot.values[key] as number)
    : fallback
export const settingText = (
  snapshot: ConfigurationSnapshot | undefined,
  key: string,
  fallback: string,
) =>
  typeof snapshot?.values[key] === 'string'
    ? (snapshot.values[key] as string)
    : fallback
