import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../apps/', import.meta.url))
const check = process.argv.includes('--check')
for (const app of await readdir(root)) {
  let svg
  try {
    svg = await readFile(join(root, app, 'icon.svg'))
  } catch (error) {
    if (error.code === 'ENOENT') {
      continue
    }
    throw error
  }
  const source = `// Generated by pnpm apps:icons from apps/${app}/icon.svg; do not edit.\nexport const applicationIcon = 'data:image/svg+xml;base64,${svg.toString('base64')}'\n`
  const target = join(root, app, 'contracts/src/icon.ts')
  if (check) {
    if (await readFile(target, 'utf8') !== source) {
      throw new Error(`${app}: run pnpm apps:icons to synchronize the icon`)
    }
  } else {
    await writeFile(target, source)
  }
}
